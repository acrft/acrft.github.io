function toggleMenu() {
    sideMenu?.classList.toggle("active");
    menuOverlay?.classList.toggle("active");
}

async function updateServerStatus() {
    try {
        const start = performance.now();
        const res = await fetch("https://api.mcstatus.io/v2/status/java/amc.falix.gg");
        const data = await res.json();
        const mcIcon = document.getElementById("mc-icon");

        mcIcon.src = data.icon || "images/logo.webp";
        const motd = Array.isArray(data.motd?.html) ? data.motd.html.join("<br>") : data.motd?.html || "";
        const ping = Math.round(performance.now() - start);

        if (!data.online) {
            setOfflineUI();
            return;
        }

        if (mcPlayers) mcPlayers.textContent = `${data.players.online}/${data.players.max}`;
        if (mcPing) mcPing.textContent = `${ping} ms`;

        const bars = document.querySelectorAll(".mc-ping span");
        mcStatus.innerHTML = motd;

        let level = 5;

        if (data.online === false) {
            level = 0;
        } else if (ping >= 1000) {
            level = 1;
        } else if (ping >= 600) {
            level = 2;
        } else if (ping >= 300) {
            level = 3;
        } else if (ping >= 150) {
            level = 4;
        }

        bars.forEach((bar, i) => {
            bar.style.opacity = i < level ? 1 : .18;
            bar.style.background = data.online ? "#55ff55" : "#ff5555";
        });

        if (mcOnlinePlayers) {
            const players = data.players?.list || [];
            mcOnlinePlayers.innerHTML = players.map(player =>
                `<div class="mc-player"><img src="${getHead(player.name_clean)}"><span>${player.name_clean}</span></div>`
            ).join("");
        }
    } catch (e) {
        setOfflineUI();
    }
}

let skins = {};

async function loadSkins() {
    try {
        const res = await fetch(`https://amc1.falix.org/skins.json?t=${Date.now()}`);
        skins = await res.json();
    } catch (e) {
        console.error("loadSkins error:", e);
        skins = {};
    }
}

function getHead(player) {
    const data = skins[player] || skins[player.toLowerCase()];

    if (!data) {
        return `https://mc-heads.net/avatar/${encodeURIComponent(player)}/16`;
    }

    try {
        const decoded = JSON.parse(atob(data.value));
        const texture = decoded.textures.SKIN.url.split("/").pop();
        return `https://mc-heads.net/head/${texture}/16`;
    } catch {
        return `https://mc-heads.net/avatar/${encodeURIComponent(player)}/16`;
    }
}

function updateContent() {
    document.documentElement.lang = currentLang;
    document.documentElement.dir = currentLang === "ar" ? "rtl" : "ltr";

    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.dataset.i18n;
        const value = translations[currentLang][key];

        if (value !== undefined) {
            el.textContent = value;
        }
    });

    updateServerStatus();
}

function toggleLanguage() {
    currentLang = currentLang === "ar" ? "en" : "ar";
    localStorage.setItem("lang", currentLang);
    updateContent();
}

function copyIP() {
    navigator.clipboard.writeText("amc.falix.gg");

    if (toast) {
        toast.textContent = translations[currentLang].toastMsg;
        toast.classList.add("show");
        setTimeout(() => toast.classList.remove("show"), 3000);
    }
}

window.addEventListener("scroll", () => {
    const progress = document.getElementById("scroll-progress");
    if (!progress) return;

    const max = document.documentElement.scrollHeight - window.innerHeight;
    const percent = max > 0 ? window.scrollY / max * 100 : 0;
    progress.style.width = percent + "%";
});

window.addEventListener("load", () => {
    updateContent();
    loadSkins();
    setInterval(updateServerStatus, 5000);
});

document.getElementById("startServer").onclick = async () => {
    const status = document.getElementById("status");
    const btn = document.getElementById("startServer");

    try {
        btn.disabled = true;

        status.textContent = currentLang === "ar"
            ? "⏳ جاري طلب تشغيل السيرفر..."
            : "⏳ Requesting server start...";

        const r = await fetch("https://hidden-wind-cca1.eldinalam91.workers.dev/", {
            method: "POST"
        });

        const data = await r.json().catch(() => ({}));
        const error = data.error || {};

        if (r.ok) {
            status.textContent = currentLang === "ar"
                ? "✅ تم إرسال طلب تشغيل السيرفر"
                : "✅ Server start request sent";
            return;
        }

        if (error.action_url) {
            status.textContent = currentLang === "ar"
                ? "🔐 افتح رابط التحقق ثم حاول تشغيل السيرفر مرة أخرى"
                : "🔐 Complete the verification, then try starting the server again";

            window.open(error.action_url, "_blank");
            return;
        }

        status.textContent = error.message ||
            data.message ||
            (currentLang === "ar"
                ? "❌ حدث خطأ أثناء تشغيل السيرفر"
                : "❌ An error occurred while starting the server");

    } catch (e) {
        console.error("Start server error:", e);

        status.textContent = currentLang === "ar"
            ? "❌ تعذر الاتصال بالخادم"
            : "❌ Could not connect to the server";

    } finally {
        btn.disabled = false;
    }
};